def runs(par, text, size=None, color=None, italic=False):
    for i, ch in enumerate(re.split(r"\*\*", text)):
        if ch:
            r = par.add_run(ch)
            r.bold, r.italic = i % 2 == 1, italic
            if size:
                r.font.size = Pt(size)
            if color is not None:
                r.font.color.rgb = color
    return par


def p(text, left=False):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.LEFT if left else WD_ALIGN_PARAGRAPH.JUSTIFY
    if not left:
        par.paragraph_format.first_line_indent = Cm(0.75)
    return runs(par, text)


def h(level, text, newpage=False):
    hp = doc.add_heading(text, level)
    if newpage:
        hp.paragraph_format.page_break_before = True


def bullets(items):
    for it in items:
        par = doc.add_paragraph(style="List Bullet")
        par.paragraph_format.space_after = Pt(3)
        runs(par, it)


def shade(cell, fill):
    cell._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:color="auto" w:fill="{fill}"/>'))


def fixed(t, widths):
    t.autofit = False
    t._tbl.tblPr.append(parse_xml(f'<w:tblLayout {nsdecls("w")} w:type="fixed"/>'))
    for j, w in enumerate(widths):
        t.columns[j].width = Cm(w)


def table(headers, rows, widths, caption, align=None, size=9.5):
    CNT["t"] += 1
    cp = doc.add_paragraph()
    cp.paragraph_format.keep_with_next = True
    runs(cp, f"Таблица Д{CNT['t']} — {caption}", size=10, italic=True)
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    fixed(t, widths)
    al = align or ["L"] + ["C"] * (len(headers) - 1)
    for j, hd in enumerate(headers):
        c = t.cell(0, j)
        c.width = Cm(widths[j])
        shade(c, "0E7C86")
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        runs(c.paragraphs[0], f"**{hd}**", size=size, color=RGBColor(0xFF, 0xFF, 0xFF))
    for i, row in enumerate(rows, 1):
        for j, val in enumerate(row):
            c = t.cell(i, j)
            c.width = Cm(widths[j])
            if i % 2 == 0:
                shade(c, "F2F6F7")
            par = c.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            par.alignment = {"L": WD_ALIGN_PARAGRAPH.LEFT, "C": WD_ALIGN_PARAGRAPH.CENTER}[al[j]]
            runs(par, str(val), size=size)
    t.rows[0]._tr.get_or_add_trPr().append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def figure(path, caption, width=15.5):
    CNT["f"] += 1
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.keep_with_next = True
    par.add_run().add_picture(path, width=Cm(width))
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    runs(cp, f"Рисунок Д{CNT['f']} — {caption}", size=10, italic=True)


def callout(title, lines):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    fixed(t, [TW])
    c = t.cell(0, 0)
    shade(c, "E3F1F2")
    runs(c.paragraphs[0], f"**{title}**", color=C_TEAL)
    for ln in lines:
        q = c.add_paragraph()
        q.paragraph_format.space_after = Pt(3)
        runs(q, ln)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


