def name(nm, ws, c):
    wb.defined_names[nm] = DefinedName(nm, attr_text=f"'{ws.title}'!{absolute_coordinate(c)}")


def put(ws, c, v, font=F, fmt=None, fill=None, al=None, b=False):
    cell = ws[c]
    cell.value = v
    cell.font = font
    if fmt:
        cell.number_format = fmt
    if fill:
        cell.fill = fill
    if al:
        cell.alignment = al
    if b:
        cell.border = BD
    return cell


def hdr(ws, r, labels, c0=1):
    for i, t in enumerate(labels):
        c = ws.cell(row=r, column=c0 + i, value=t)
        c.font, c.fill, c.alignment, c.border = FB, HEAD, CE, BD


def title(ws, t, sub=None):
    put(ws, "A1", t, FT)
    if sub:
        put(ws, "A2", sub, FN_)


def widths(ws, d):
    for k, v in d.items():
        ws.column_dimensions[k].width = v


def R(ws, c):
    return f"'{ws.title}'!{absolute_coordinate(c)}"


