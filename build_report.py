def shade(cell, fill):
    cell._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:color="auto" w:fill="{fill}"/>'))


def fixed_widths(t, widths):
    """Фиксированная раскладка: ширины колонок соблюдают и Word, и LibreOffice."""
    t.autofit = False
    t._tbl.tblPr.append(parse_xml(f'<w:tblLayout {nsdecls("w")} w:type="fixed"/>'))
    for j, w in enumerate(widths):
        t.columns[j].width = Cm(w)


def callout(title, lines, fill="E3F1F2"):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    fixed_widths(t, [TEXT_W])
    c = t.cell(0, 0)
    c.width = Cm(TEXT_W)
    shade(c, fill)
    par = c.paragraphs[0]
    runs(par, f"**{title}**", color=C_TEAL)
    for ln in lines:
        q = c.add_paragraph()
        q.paragraph_format.space_after = Pt(3)
        runs(q, ln)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


