def runs(par, text, size=None, color=None, italic=False):
    """Текст с разметкой **жирный**."""
    for i, chunk in enumerate(re.split(r"\*\*", text)):
        if not chunk:
            continue
        r = par.add_run(chunk)
        r.bold = i % 2 == 1
        r.italic = italic
        if size:
            r.font.size = Pt(size)
        if color is not None:
            r.font.color.rgb = color
    return par


def p(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, **kw):
    par = doc.add_paragraph()
    par.alignment = align
    par.paragraph_format.first_line_indent = Cm(0.75) if align == WD_ALIGN_PARAGRAPH.JUSTIFY else None
    return runs(par, text, **kw)


